#pragma once

#include <cstdint>

// Отклик строки на быстрые включения питания (power_cycles.h): человек у
// строки должен видеть, что включение засчитано, иначе он выключит её наугад.

namespace ledcast {

// Окно включения в фоне, загрузку не держит. Пока показывать нечего — ни шоу,
// ни потока, ни теста, — на панели три квадрата: закрашено столько, какое это
// включение подряд, полоса под ними тает до конца окна. Конец окна
// закрывает серию: следующее включение считается снова с первого.
void power_cycle_window_start(uint8_t cycles, bool output_ready);

// Автономный запуск без шоу: три зелёных квадрата — строка в своей сети.
// Кадр стоит, пока его не сменит поток или тест.
void power_cycle_standalone_mark();

}  // namespace ledcast
